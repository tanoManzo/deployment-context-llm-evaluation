"""Recover plotted values from the vector PDF figures produced by the original
results pipeline.

Some aggregated values used in the revision (GSM8K end-to-end latency for the
re-run Edge/Local-CPU configurations, GSM8K peak system RAM, and GPU energy per
GSM8K request) are present in the vector figures generated by the original
pipeline but not in the exported LaTeX tables. Because the figures are vector
graphics, marker and polyline coordinates can be inverted exactly through the
axis tick calibration. The recovered values are cross-checked against values
that appear both in the figures and in the tables (see ``validate``).

Usage:
    python recover_figure_values.py            # writes data/recovered_from_figures.csv
"""
from __future__ import annotations

import csv
from pathlib import Path

import fitz  # PyMuPDF
import numpy as np

ROOT = Path(__file__).resolve().parent
FIG = ROOT.parent / "figures"
OUT = ROOT / "data" / "recovered_from_figures.csv"

EDGE = ["Gemma 3 1B (Q8)", "Llama 3.2 1B (Q4)", "Phi-4 Mini 3.8B (Q4)", "SmolLM3 3B (Q4)"]
CPU = ["Gemma 3 1B (Q8)", "Llama 3.2 1B (Q8)", "Ministral 3 3B (Q4)", "Phi-4 Mini 3.8B (Q4)"]
GPU = [
    "Apertus 70B (bf16)", "Granite 4 H-Tiny (bf16)", "Kimi Linear 48B-A3B (bf16)",
    "Llama 3.2 1B (bf16)", "Llama 3.3 70B (FP8)", "Ministral 3 14B", "Ministral 3 3B (AWQ)",
    "Ministral 3 8B (AWQ)", "Phi-4 14B (bf16)", "Phi-4 Mini 3.8B (GPTQ-4)",
    "Phi-4 Mini 3.8B (bf16)", "Qwen 2.5 1.5B (bf16)", "Qwen 2.5 7B (AWQ)",
    "Qwen 3 30B-A3B (bf16)", "Qwen 3 4B (AWQ)",
]


def _num(word: str) -> float | None:
    try:
        return float(word.replace("\u2212", "-"))
    except ValueError:
        return None


def _tick_lines(page) -> list[float]:
    """y-coordinates of short horizontal axis tick marks."""
    return [d["rect"].y0 for d in page.get_drawings()
            if d["items"][0][0] == "l" and len(d["items"]) == 1
            and abs(d["rect"].height) < 0.01 and 2.4 < d["rect"].width < 4]


def _snap(ticks: list[tuple[float, float]], lines: list[float], tol: float = 4.0):
    """Replace label-centre positions by the nearest tick-mark position.

    Tick labels are not exactly centred on their tick marks; snapping removes a
    small systematic offset (about 0.3 pt) from the calibration.
    """
    out = []
    for pos, val in ticks:
        near = min(lines, key=lambda y: abs(y - pos))
        out.append((near if abs(near - pos) <= tol else pos, val))
    return out


def _calibrate(ticks: list[tuple[float, float]]) -> np.ndarray:
    """Linear map from page coordinate to data value fitted on tick labels."""
    pos, val = zip(*ticks)
    return np.polyfit(pos, val, 1)


def _ticks(words, x_range, y_range, axis):
    out = []
    for w in words:
        v = _num(w[4])
        if v is None:
            continue
        cx, cy = (w[0] + w[2]) / 2, (w[1] + w[3]) / 2
        if x_range[0] <= cx <= x_range[1] and y_range[0] <= cy <= y_range[1]:
            out.append((cx if axis == "x" else cy, v))
    return out


def recover_gsm8k_latency_accuracy():
    """Scatter markers of figure_06_gsm8k_accuracy_latency_frontiers.pdf."""
    page = fitz.open(FIG / "figure_06_gsm8k_accuracy_latency_frontiers.pdf")[0]
    words = page.get_text("words")
    markers = [
        d for d in page.get_drawings()
        if (d["type"] == "fs" and len(d["items"]) == 4 and round(d["rect"].width, 1) == 8.7)
        or (d["type"] == "s" and len(d["items"]) == 8 and round(d["rect"].width, 1) == 4.7)
    ]
    panels = {"Edge": (0, 185, 183), "Local CPU": (185, 352, 349), "GPU server": (352, 530, 516)}
    rows = []
    for ctx, (y0, y1, ytick_row) in panels.items():
        xt = _ticks(words, (28, 500), (ytick_row - 14, ytick_row), "x")
        yt = _snap(_ticks(words, (10, 26), (y0, y1), "y"), _tick_lines(page))
        ax, ay = _calibrate(xt), _calibrate(yt)
        for m in markers:
            r = m["rect"]
            cx, cy = (r.x0 + r.x1) / 2, (r.y0 + r.y1) / 2
            if y0 < cy < y1:
                rows.append({
                    "context": ctx,
                    "latency_s": float(np.polyval(ax, cx)),
                    "accuracy": float(np.polyval(ay, cy)),
                    "pareto_marker": m["type"] == "fs",
                })
    return rows


def recover_gsm8k_ram_energy():
    """Polylines of figure_07_gsm8k_accuracy_memory_energy_dual_axis.pdf."""
    page = fitz.open(FIG / "figure_07_gsm8k_accuracy_memory_energy_dual_axis.pdf")[0]
    words = page.get_text("words")
    lines = []
    for d in page.get_drawings():
        if d["type"] == "s" and len(d["items"]) >= 3 and all(it[0] == "l" for it in d["items"]):
            pts = [d["items"][0][1]] + [it[2] for it in d["items"]]
            lines.append([(p.x, p.y) for p in pts])
    lines.sort(key=lambda pts: (len(pts), pts[0][0]))
    edge_line, cpu_line, gpu_line = lines[0], lines[1], lines[2]
    # Right-axis calibrations (tick labels located right of each panel).
    lines_y = _tick_lines(page)
    edge_ax = _calibrate(_snap(_ticks(words, (215, 226), (20, 150), "y"), lines_y))
    cpu_ax = _calibrate(_snap(_ticks(words, (465, 482), (20, 150), "y"), lines_y))
    gpu_ax = _calibrate(_snap(_ticks(words, (465, 485), (225, 380), "y"), lines_y))
    rows = []
    for names, line, cal, ctx, metric in (
        (EDGE, edge_line, edge_ax, "Edge", "peak_ram_gib"),
        (CPU, cpu_line, cpu_ax, "Local CPU", "peak_ram_gib"),
        (GPU, gpu_line, gpu_ax, "GPU server", "gpu_energy_j"),
    ):
        assert len(names) == len(line), (ctx, len(line))
        for name, (_, y) in zip(names, line):
            rows.append({"context": ctx, "model": name, "metric": metric,
                         "value": float(np.polyval(cal, y))})
    return rows


def recover_reported_throughput():
    """Bar outlines of figure_05_sustained_throughput_across_contexts.pdf (log axis).

    Edge/Local-CPU bars are active-generation tokens/s; GPU bars are run-level
    sustained tokens/s (as stated in the figure caption of the pipeline).
    """
    page = fitz.open(FIG / "figure_05_sustained_throughput_across_contexts.pdf")[0]
    words = page.get_text("words")
    bars = [d["rect"] for d in page.get_drawings()
            if d["type"] == "s" and d["items"][0][0] == "re" and round(d["rect"].width, 1) == 13.5]
    lines_y = _tick_lines(page)
    ten = sorted(_snap([((w[1] + w[3]) / 2, 10) for w in words if w[4] == "10" and w[0] < 30], lines_y))
    hundred = sorted(_snap([((w[1] + w[3]) / 2, 100) for w in words if w[4] == "100" and w[0] < 30], lines_y))
    ten = [t[0] for t in ten]
    hundred = [t[0] for t in hundred]
    names = EDGE + CPU + GPU
    rows = []
    for k, ds in enumerate(("Dolly", "GSM8K", "HellaSwag", "MMLU")):
        y10, y100 = ten[k], hundred[k]
        upper = hundred[k + 1] - 20 if k + 1 < len(hundred) else float("inf")
        panel = sorted((b for b in bars if y100 - 20 < b.y0 < upper), key=lambda b: b.x0)
        assert len(panel) == len(names), (ds, len(panel))
        for i, (name, b) in enumerate(zip(names, panel)):
            ctx = "Edge" if i < 4 else ("Local CPU" if i < 8 else "GPU server")
            val = 10 ** (1 + (y10 - b.y0) / (y10 - y100))
            rows.append({"context": ctx, "model": name, "dataset": ds, "value": val})
    return rows


def validate(lat_rows):
    """Cross-check recovered latencies against values also present in tables."""
    known = {  # (context, latency_s) from tables/table_05 and thesis Table 8.2
        ("Edge", 16.013), ("Edge", 42.040), ("Local CPU", 18.629),
        ("GPU server", 1.098), ("GPU server", 7.058), ("GPU server", 10.969),
    }
    worst = 0.0
    for ctx, val in known:
        best = min(abs(r["latency_s"] - val) for r in lat_rows if r["context"] == ctx)
        worst = max(worst, best)
    return worst


def main():
    lat = recover_gsm8k_latency_accuracy()
    err = validate(lat)
    ram_energy = recover_gsm8k_ram_energy()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["figure", "context", "model", "metric", "value"])
        for r in sorted(lat, key=lambda r: (r["context"], r["latency_s"])):
            w.writerow(["figure_06", r["context"], "", "gsm8k_latency_s", f"{r['latency_s']:.3f}"])
            w.writerow(["figure_06", r["context"], "", "gsm8k_accuracy", f"{r['accuracy']:.3f}"])
        for r in ram_energy:
            w.writerow(["figure_07", r["context"], r["model"], r["metric"], f"{r['value']:.3f}"])
        for r in recover_reported_throughput():
            w.writerow(["figure_05", r["context"], r["model"],
                        f"reported_tokens_per_s:{r['dataset']}", f"{r['value']:.3f}"])
    print(f"wrote {OUT}  (max |error| on cross-checked latencies: {err * 1000:.1f} ms)")
    for r in ram_energy:
        print(f"  {r['context']:<10} {r['model']:<28} {r['metric']:<14} {r['value']:9.2f}")


if __name__ == "__main__":
    main()
